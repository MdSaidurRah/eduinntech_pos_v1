    public static function all(): array
    {
        $out = [];
        foreach (LangTrans::$mainTranslations as $group => $items) {
            foreach ($items as $key => $value) {
                $out[$group][$key] = self::$direct[$group][$key] ?? self::auto((string) $value);
            }
        }

        return $out;
    }

    public static function auto(string $english): string
    {
        if (isset(self::$phrases[$english])) {
            return self::$phrases[$english];
        }

        $patterns = [
            '/^Add New (.+)$/' => 'নতুন {0} যোগ করুন',
            '/^Edit (.+)$/' => '{0} সম্পাদনা',
            '/^(.+) Created Successfully$/' => '{0} সফলভাবে তৈরি হয়েছে',
            '/^(.+) Updated Successfully$/' => '{0} সফলভাবে আপডেট হয়েছে',
            '/^(.+) Deleted Successfully$/' => '{0} সফলভাবে মুছে ফেলা হয়েছে',
            '/^(.+) Details$/' => '{0} বিবরণ',
            '/^Are you sure you want to delete this (.+)\?$/' => 'আপনি কি এই {0} মুছে ফেলতে চান?',
            '/^Are you sure you want to delete selected (.+)\?$/' => 'আপনি কি নির্বাচিত {0} মুছে ফেলতে চান?',
            '/^Import (.+)$/' => '{0} ইমপোর্ট করুন',
            '/^Add (.+)$/' => '{0} যোগ করুন',
        ];

        foreach ($patterns as $pattern => $template) {
            if (preg_match($pattern, $english, $matches)) {
                $entity = self::$entities[$matches[1]] ?? self::$phrases[$matches[1]] ?? $matches[1];

                return str_replace('{0}', $entity, $template);
            }
        }

        return $english;
    }

